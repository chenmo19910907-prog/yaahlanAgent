STRATEGY_FILLS = {
    "每版必测": PatternFill("solid", fgColor="E2EFDA"),
    "隔版抽测": PatternFill("solid", fgColor="FFF2CC"),
    "触发式": PatternFill("solid", fgColor="FCE4D6"),
    "触发式(内网)": PatternFill("solid", fgColor="FCE4D6"),
    "大版本/专项": PatternFill("solid", fgColor="DDEBF7"),
    "审核专项": PatternFill("solid", fgColor="E4DFEC"),
}


def write_baseline(output_path: Path) -> dict[str, int]:
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "版本回归case"
    headers = ["级别", "一级模块", "二级模块", "执行case", "预期结果", "回归策略", "调整说明"]
    ws.append(headers)
    header_fill = PatternFill("solid", fgColor="4472C4")
    header_font = Font(color="FFFFFF", bold=True)
    for col in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=col)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center")

    for case in BASELINE_CASES:
        ws.append(list(case))

    for row_idx in range(2, ws.max_row + 1):
        strategy = str(ws.cell(row=row_idx, column=6).value or "")
        fill = STRATEGY_FILLS.get(strategy)
        if fill:
            for col in range(1, len(headers) + 1):
                ws.cell(row=row_idx, column=col).fill = fill

    widths = [6, 32, 18, 52, 36, 14, 28]
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"

    counter: dict[str, int] = {}
    for case in BASELINE_CASES:
        counter[case[5]] = counter.get(case[5], 0) + 1

    ws2 = wb.create_sheet("策略统计")
    ws2.append(["回归策略", "条数"])
    for k, v in sorted(counter.items(), key=lambda x: -x[1]):
        ws2.append([k, v])
    p0 = sum(1 for c in BASELINE_CASES if c[0] == 1)
    p1 = sum(1 for c in BASELINE_CASES if c[0] == 2)
    p2 = sum(1 for c in BASELINE_CASES if c[0] == 3)
    must = counter.get("每版必测", 0)
    ws2.append([])
    ws2.append(["合计", len(BASELINE_CASES)])
    ws2.append(["P0(级别1)", p0])
    ws2.append(["P1(级别2)", p1])
    ws2.append(["P2(级别3)", p2])
    ws2.append(["每版必测条数", must])
    ws2.append(["导出时间", datetime.now().strftime("%Y-%m-%d %H:%M:%S")])

    ws3 = wb.create_sheet("使用说明")
    for n in [
        "Yaahlan 发版回归基线用例（auto-generate-testcase 生成）",
        "",
        "发版前执行建议：",
        "  1. 筛选「回归策略=每版必测」全部执行",
        "  2. 对照本版 PRD 变更，补充 [回归] 强关联模块",
        "  3. 对照 bug-kb / online-kb 严重项补充历史翻车场景",
        "  4. 隔版抽测 / 触发式 / 大版本专项 按本版情况选用",
        "",
        "级别：1=P0  2=P1  3=P2",
        "送礼模块请使用 199 或 136 号段账号执行",
        "公会模块需内网账号 16028887200",
    ]:
        ws3.append([n])

    output_path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(output_path)
    return {"total": len(BASELINE_CASES), "must": must, "p0": p0}


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser(description="生成发版回归基线用例 Excel")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    stats = write_baseline(args.output)
    print(f"已生成: {args.output}")
    print(f"合计 {stats['total']} 条，每版必测 {stats['must']} 条，P0 {stats['p0']} 条")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

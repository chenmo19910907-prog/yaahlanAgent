def render() -> str:
    lines = [
        "# Yaahlan 【币商助理】测试用例\n\n",
        "| 一级模块 | 二级模块 | 测试步骤 | 预期结果 |\n",
        "|----------|----------|----------|----------|\n",
    ]
    prev_l1, prev_l2 = "", ""
    for l1, l2, step, exp in C:
        out_l1 = l1 if l1 and l1 != prev_l1 else ""
        if l1:
            prev_l1, prev_l2 = l1, ""
        out_l2 = ""
        if l2:
            if l2 != prev_l2 or out_l1:
                out_l2 = l2
                prev_l2 = l2
        lines.append(f"| {out_l1} | {out_l2} | {step} | {exp} |\n")
    return "".join(lines)


def main() -> None:
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {len(C)} cases -> {OUT}")


if __name__ == "__main__":
    main()
